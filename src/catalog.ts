function measures(overrides: Record<string, Partial<ParamSpec>> = {}, at = AT): Measurement[] {
  return Object.entries(BASE_PARAMS).map(([param_code, base]) => {
    const next = overrides[param_code] ?? {};
    return {
      param_code,
      measured_value: next.v ?? base.v,
      unit: next.u ?? base.u,
      measured_at: at,
      status: next.s ?? base.s ?? "OK",
    };
  });
}

