function asset(
  pond_id: string,
  kind: AssetKind,
  name: string,
  location_label: string,
  status: AssetStatus,
  extra: Partial<Asset> = {},
): Asset {
  return {
    id: extra.id ?? `${pond_id}-${kind}-${location_label}`,
    pond_id,
    kind,
    name,
    location_label,
    status,
    last_seen: extra.last_seen ?? AT,
    device_code: extra.device_code,
  };
}

